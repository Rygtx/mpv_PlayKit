inline bool BuildFonts(float dpiScale, ImFont **outUI, ImFont **outMono) noexcept {
    char winDir[MAX_PATH];
    GetWindowsDirectoryA(winDir, MAX_PATH);
    std::string fontsDir = std::string(winDir) + "\\Fonts\\";

    // Win11 ships the variable font; fall back to the static one on Win10
    std::string uiFontPath = fontsDir + "SegUIVar.ttf";
    FILE *probe = nullptr;
    if (fopen_s(&probe, uiFontPath.c_str(), "rb") != 0 || !probe) {
        uiFontPath = fontsDir + "segoeui.ttf";
    } else {
        fclose(probe);
    }

    std::vector<uint8_t> uiData;
    {
        FILE *f = nullptr;
        if (fopen_s(&f, uiFontPath.c_str(), "rb") != 0 || !f) return false;
        fseek(f, 0, SEEK_END);
        const long size = ftell(f);
        fseek(f, 0, SEEK_SET);
        uiData.resize(size);
        fread(uiData.data(), 1, size, f);
        fclose(f);
    }

    ImFontAtlas &fontAtlas = *ImGui::GetIO().Fonts;
    fontAtlas.Flags |= ImFontAtlasFlags_NoPowerOfTwoHeight;

    const float fontSize = 18 * dpiScale;

    ImFontConfig config;
    config.FontDataOwnedByAtlas = false;

    // fontUI: Basic Latin + → (U+2192, 分辨率行用) + COLOR_INDICATOR
    ImWchar uiRanges[7]{ 0x20, 0x7E, 0x2192, 0x2192, COLOR_INDICATOR_W, COLOR_INDICATOR_W, 0 };
    *outUI = fontAtlas.AddFontFromMemoryTTF(
        reinterpret_cast<void *>(uiData.data()), static_cast<int>(uiData.size()),
        fontSize, &config, uiRanges);
    if (!*outUI) return false;

    // merge msyh.ttc (FontNo 1 = Microsoft YaHei UI) for Chinese
    {
        char msyhPath[MAX_PATH];
        GetWindowsDirectoryA(msyhPath, MAX_PATH);
        strcat_s(msyhPath, "\\Fonts\\msyh.ttc");
        FILE *probe2 = nullptr;
        if (fopen_s(&probe2, msyhPath, "rb") == 0 && probe2) {
            fclose(probe2);
            // official simplified-Chinese glyph set (same table as Magpie)
            const ImWchar *zh = GetGlyphRangesChineseSimplifiedOfficial();
            config.MergeMode = true;
            config.FontNo = 1;
            config.FontDataOwnedByAtlas = true;
            *outUI = fontAtlas.AddFontFromFileTTF(msyhPath, fontSize, &config, zh);
            config.FontDataOwnedByAtlas = false;
            config.FontNo = 0;
            config.MergeMode = false;
            if (!*outUI) return false;
        }
    }

    // fontMono: digits monospaced
    {
        ImFontConfig mconfig;
        mconfig.FontDataOwnedByAtlas = false;
        mconfig.GlyphMinAdvanceX = mconfig.GlyphMaxAdvanceX = fontSize * 0.42f;
        *outMono = fontAtlas.AddFontFromMemoryTTF(
            reinterpret_cast<void *>(uiData.data()), static_cast<int>(uiData.size()),
            fontSize, &mconfig, NUMBER_RANGES);
        if (!*outMono) return false;
        mconfig.MergeMode = true;
        mconfig.GlyphMinAdvanceX = 0;
        mconfig.GlyphMaxAdvanceX = 3.99e3f;
        *outMono = fontAtlas.AddFontFromMemoryTTF(
            reinterpret_cast<void *>(uiData.data()), static_cast<int>(uiData.size()),
            fontSize, &mconfig, NOT_NUMBER_RANGES);
        if (!*outMono) return false;
    }

    // Build while uiData is still alive (FontDataOwnedByAtlas = false)
    if (!fontAtlas.Build()) return false;
    return true;
}

